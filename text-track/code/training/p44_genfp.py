#!/usr/bin/env python3
"""Phase 44: generator-trace NLL fingerprint (NEW orthogonal info source).

Idea: AI text is generated by a specific LLM family -> that family's NLL is LOWER than
other models (self-evidence). Compute per text, for TWO Qwen models (1.5B + 7B):
  nll_15 = per-token NLL using 1.5B (base or instruct? use Instruct for both)
  nll_7  = per-token NLL using 7B
  ratio / diff / rank-diff of (nll_15, nll_7) across the doc -> "generator signature".
Features per text (13-dim):
  nll15_mean, nll15_std, nll15_p90,
  nll7_mean, nll7_std, nll7_p90,
  diff_mean(n15-n7), diff_std, diff quantile .25/.75,
  ratio_mean(n15/n7), ppl15, ppl7
Train 5-fold LGB on official y -> runs/genfp_oof.npy + genfp_replay.npy.
Runs on OLD server GPU1 (cuda:1) once free. /usr/bin/python3.10 (has lgb).
"""
import sys
sys.stdout.reconfigure(encoding="utf-8", errors="replace")
from pathlib import Path
import glob
import numpy as np
import pandas as pd
import torch
from transformers import AutoModelForCausalLM, AutoTokenizer

BASE = Path("/data/湾区杯")
RUNS = BASE / "文本赛道" / "runs"
INIT = BASE / "initial_text"
MODELS = BASE / "文本赛道" / "models"
DEV = torch.device("cuda:1")
BS = 8
MAXLEN = 512

def main():
    sample_csv = glob.glob(str(INIT / "**" / "text_sample_data.csv"), recursive=True)[0]
    train = pd.read_csv(sample_csv, encoding="utf-8-sig")
    y = train.label.astype(int).to_numpy()
    official_texts = train.text.fillna("").astype(str).tolist()
    test = pd.read_csv(BASE / "replay_data" / "文本赛道" / "text_test.csv", encoding="utf-8-sig")
    test_texts = test.text.fillna("").astype(str).tolist()
    print("official", len(official_texts), "replay", len(test_texts), flush=True)

    tokenizer = AutoTokenizer.from_pretrained(str(MODELS / "Qwen2.5-1.5B-Instruct"), trust_remote_code=True)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token

    def nll_stats(model, texts, tag):
        model.eval()
        nlls = []
        with torch.inference_mode():
            for s in range(0, len(texts), BS):
                enc = tokenizer(texts[s:s+BS], padding=True, truncation=True, max_length=MAXLEN,
                                return_tensors="pt")
                ids = enc["input_ids"].to(DEV)
                attn = enc["attention_mask"].to(DEV)
                logits = model(ids, attention_mask=attn).logits.float()
                logp = torch.log_softmax(logits[:, :-1], dim=-1)
                tgt = ids[:, 1:]
                per = -logp.gather(2, tgt[:, :, None]).squeeze(-1)  # per-token NLL
                # mask padding positions
                m = attn[:, 1:].bool()
                for i in range(per.shape[0]):
                    v = per[i][m[i]]
                    if v.numel() == 0:
                        nlls.append(np.array([np.nan]*7))
                    else:
                        nlls.append([v.mean().item(), v.std().item(),
                                     float(torch.quantile(v, 0.9).item()), v.numel(),
                                     float(torch.quantile(v, 0.25).item()),
                                     float(torch.quantile(v, 0.75).item()), v.max().item()])
                if (s // BS) % 20 == 0:
                    print(tag, "progress", s, flush=True)
        return np.asarray(nlls, dtype=np.float64)

    m15 = AutoModelForCausalLM.from_pretrained(str(MODELS / "Qwen2.5-1.5B-Instruct"),
                                               trust_remote_code=True, torch_dtype=torch.bfloat16,
                                               attn_implementation="eager").to(DEV)
    print("1.5B loaded", flush=True)
    F15_off = nll_stats(m15, official_texts, "15b")
    F15_rep = nll_stats(m15, test_texts, "15b")
    del m15; torch.cuda.empty_cache()
    m7 = AutoModelForCausalLM.from_pretrained(str(MODELS / "Qwen2.5-7B-Instruct"),
                                              trust_remote_code=True, torch_dtype=torch.bfloat16,
                                              attn_implementation="eager").to(DEV)
    print("7B loaded", flush=True)
    F7_off = nll_stats(m7, official_texts, "7b")
    F7_rep = nll_stats(m7, test_texts, "7b")
    del m7; torch.cuda.empty_cache()

    def feats(f15, f7):
        d = f15[:, :6] - f7[:, :6]
        ratio = f15[:, 0] / np.maximum(f7[:, 0], 1e-6)
        return np.hstack([f15[:, :6], f7[:, :6], d, ratio[:, None],
                          f15[:, 6:7], f7[:, 6:7]])

    Xo = feats(F15_off, F7_off)
    Xr = feats(F15_rep, F7_rep)
    print("feats", Xo.shape, flush=True)
    np.save(RUNS / "genfp_feats_official.npy", Xo)
    np.save(RUNS / "genfp_feats_replay.npy", Xr)

    import lightgbm as lgb
    from sklearn.metrics import roc_auc_score
    folds = np.load(RUNS / "folds.npy")
    oof = np.zeros(len(y))
    tests = []
    for f in range(5):
        tr = np.flatnonzero(folds != f); va = np.flatnonzero(folds == f)
        m = lgb.LGBMClassifier(objective="binary", n_estimators=500, learning_rate=0.03,
                               num_leaves=7, max_depth=3, min_child_samples=35,
                               reg_alpha=0.5, reg_lambda=2.0, random_state=20260909+f,
                               n_jobs=8, verbosity=-1)
        m.fit(Xo[tr], y[tr])
        oof[va] = m.predict_proba(Xo[va])[:, 1]
        tests.append(m.predict_proba(Xr)[:, 1])
    rep = np.mean(tests, axis=0)
    auc = roc_auc_score(y, oof)
    print("genfp OOF AUC", round(auc, 6), flush=True)
    np.save(RUNS / "genfp_oof.npy", oof)
    np.save(RUNS / "genfp_replay.npy", rep)
    print("GENFP DONE", flush=True)

if __name__ == "__main__":
    main()
